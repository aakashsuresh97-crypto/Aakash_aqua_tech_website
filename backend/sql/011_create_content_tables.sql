-- Website content managed from the admin: testimonials, brands, FAQs, zones, static pages, AMC plans. Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS testimonial (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  customer_name VARCHAR(100) NOT NULL,
  city          VARCHAR(80) NULL,
  feedback      TEXT NOT NULL,
  rating        TINYINT UNSIGNED NOT NULL DEFAULT 5,
  image_url     VARCHAR(500) NULL,
  display_order INT NOT NULL DEFAULT 0,
  status        TINYINT(1) NOT NULL DEFAULT 1,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_testimonial_show (status, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS brand (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  slug          VARCHAR(80) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  name          VARCHAR(100) NOT NULL,
  logo_url      VARCHAR(500) NULL,
  website_url   VARCHAR(500) NULL,
  display_order INT NOT NULL DEFAULT 0,
  status        TINYINT(1) NOT NULL DEFAULT 1,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_brand_slug (slug),
  UNIQUE KEY uq_brand_name (name),
  KEY idx_brand_show (status, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS faq (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  question      VARCHAR(300) NOT NULL,
  answer        TEXT NOT NULL,
  topic         VARCHAR(60) NOT NULL DEFAULT 'general',
  display_order INT NOT NULL DEFAULT 0,
  status        TINYINT(1) NOT NULL DEFAULT 1,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_faq_show (status, topic, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS zone (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  name          VARCHAR(100) NOT NULL,
  state         VARCHAR(80) NULL,
  description   TEXT NULL,
  pin_codes     VARCHAR(500) NULL COMMENT 'comma separated',
  image_url     VARCHAR(500) NULL,
  display_order INT NOT NULL DEFAULT 0,
  status        TINYINT(1) NOT NULL DEFAULT 1,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_zone_name (name),
  KEY idx_zone_show (status, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS static_page (
  id               CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  slug             VARCHAR(100) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  title            VARCHAR(200) NOT NULL,
  content_html     MEDIUMTEXT NOT NULL COMMENT 'sanitised on save',
  banner_url       VARCHAR(500) NULL,
  seo_title        VARCHAR(255) NULL,
  meta_description VARCHAR(500) NULL,
  status           TINYINT(1) NOT NULL DEFAULT 1,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_static_page_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS amc_plan (
  id              CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  name            VARCHAR(120) NOT NULL,
  price           DECIMAL(10,2) NOT NULL,
  duration_months TINYINT UNSIGNED NOT NULL DEFAULT 12,
  visits_per_year TINYINT UNSIGNED NULL,
  description     TEXT NULL,
  features        TEXT NULL COMMENT 'one feature per line',
  display_order   INT NOT NULL DEFAULT 0,
  status          TINYINT(1) NOT NULL DEFAULT 1,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_amc_plan_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
