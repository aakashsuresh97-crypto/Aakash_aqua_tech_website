-- Homepage / promo banners. Safe to run repeatedly (CREATE TABLE IF NOT EXISTS); never drops or alters existing data.
-- image_url stores only a URL string (an upload from POST /api/uploads/images, or an external URL).
CREATE TABLE IF NOT EXISTS banner (
  id               CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  title            VARCHAR(150) NOT NULL,
  subtitle         VARCHAR(255) NULL,
  image_url        VARCHAR(500) NOT NULL,
  mobile_image_url VARCHAR(500) NULL,
  link_url         VARCHAR(500) NULL,
  button_text      VARCHAR(60) NULL,
  placement        VARCHAR(40) NOT NULL DEFAULT 'home_hero',
  display_order    INT NOT NULL DEFAULT 0,
  status           TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = active, 0 = inactive',
  starts_at        TIMESTAMP NULL DEFAULT NULL,
  ends_at          TIMESTAMP NULL DEFAULT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_banner_show (status, placement, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
