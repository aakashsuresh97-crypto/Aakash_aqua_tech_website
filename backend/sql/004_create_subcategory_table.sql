-- Subcategories. Safe to run on an existing database: only creates the table if it is missing.
-- category_id must have exactly the same type/charset/collation as category.id (CHAR(36) ascii) for the foreign key.
-- ON DELETE RESTRICT: a category that still has subcategories cannot be deleted (the API answers 409).
CREATE TABLE IF NOT EXISTS subcategory (
  id               CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  category_id      CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  subcategory_name VARCHAR(100) NOT NULL,
  description      TEXT NULL,
  image            VARCHAR(255) NULL,
  status           TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = active, 0 = inactive',
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_subcategory_category_name (category_id, subcategory_name),
  KEY idx_subcategory_status (status),
  CONSTRAINT fk_subcategory_category FOREIGN KEY (category_id) REFERENCES category (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;