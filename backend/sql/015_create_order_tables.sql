-- Cart, orders, payments, refunds, invoices. Safe to run repeatedly. Prices are GST-inclusive (as in the product API).
CREATE TABLE IF NOT EXISTS cart_item (
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  product_id  CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  quantity    INT UNSIGNED NOT NULL DEFAULT 1,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (customer_id, product_id),
  CONSTRAINT fk_cart_customer FOREIGN KEY (customer_id) REFERENCES customer (id) ON DELETE CASCADE,
  CONSTRAINT fk_cart_product FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Atomic number sequences (order numbers and invoice numbers restart every financial year).
CREATE TABLE IF NOT EXISTS number_sequence (
  name    VARCHAR(30) CHARACTER SET ascii NOT NULL,
  fy      VARCHAR(9) CHARACTER SET ascii NOT NULL,
  last_no INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (name, fy)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
  id                  CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  order_number        VARCHAR(30) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  customer_id         CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  status              ENUM('placed','confirmed','shipped','delivered','cancelled') NOT NULL DEFAULT 'placed',
  payment_method      ENUM('razorpay','cod') NOT NULL,
  payment_status      ENUM('pending','paid','failed','refunded','partially_refunded') NOT NULL DEFAULT 'pending',
  subtotal            DECIMAL(12,2) NOT NULL,
  discount_total      DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_total      DECIMAL(12,2) NOT NULL DEFAULT 0,
  total               DECIMAL(12,2) NOT NULL,
  refund_amount       DECIMAL(12,2) NOT NULL DEFAULT 0,
  ship_name           VARCHAR(100) NOT NULL,
  ship_mobile         CHAR(10) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  ship_line1          VARCHAR(200) NOT NULL,
  ship_line2          VARCHAR(200) NULL,
  ship_city           VARCHAR(80) NOT NULL,
  ship_state          VARCHAR(80) NOT NULL,
  ship_pin            CHAR(6) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  customer_notes      VARCHAR(500) NULL,
  admin_notes         VARCHAR(1000) NULL,
  tracking_info       VARCHAR(255) NULL,
  razorpay_order_id   VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  razorpay_payment_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  invoice_number      VARCHAR(30) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  invoice_date        DATE NULL,
  placed_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmed_at        TIMESTAMP NULL DEFAULT NULL,
  shipped_at          TIMESTAMP NULL DEFAULT NULL,
  delivered_at        TIMESTAMP NULL DEFAULT NULL,
  cancelled_at        TIMESTAMP NULL DEFAULT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_number (order_number),
  UNIQUE KEY uq_orders_invoice (invoice_number),
  UNIQUE KEY uq_orders_razorpay_order (razorpay_order_id),
  KEY idx_orders_customer (customer_id, placed_at),
  KEY idx_orders_status (status, placed_at),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- A snapshot of what was bought: name, price and GST are copied so later product edits never change an old order.
CREATE TABLE IF NOT EXISTS order_items (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  order_id      CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  product_id    CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  product_name  VARCHAR(200) NOT NULL,
  sku           VARCHAR(64) NULL,
  brand         VARCHAR(100) NULL,
  image_url     VARCHAR(500) NULL,
  quantity      INT UNSIGNED NOT NULL,
  unit_price    DECIMAL(10,2) NOT NULL COMMENT 'GST-inclusive price paid per unit',
  mrp           DECIMAL(10,2) NOT NULL,
  gst_percent   DECIMAL(5,2) NOT NULL DEFAULT 0,
  line_total    DECIMAL(12,2) NOT NULL,
  taxable_value DECIMAL(12,2) NOT NULL,
  gst_amount    DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_order_items_order (order_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment (
  id                  CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  order_id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  provider            ENUM('razorpay','cod') NOT NULL,
  provider_order_id   VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  provider_payment_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  amount              DECIMAL(12,2) NOT NULL,
  currency            CHAR(3) NOT NULL DEFAULT 'INR',
  status              ENUM('created','paid','failed') NOT NULL DEFAULT 'created',
  signature_verified  TINYINT(1) NOT NULL DEFAULT 0,
  error_message       VARCHAR(500) NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_payment_order (order_id),
  KEY idx_payment_provider_order (provider_order_id),
  CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS refund (
  id                 CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  order_id           CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  provider_refund_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  amount             DECIMAL(12,2) NOT NULL,
  reason             VARCHAR(255) NULL,
  status             ENUM('processed','manual','failed') NOT NULL DEFAULT 'processed',
  created_by         CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_refund_order (order_id),
  CONSTRAINT fk_refund_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Razorpay webhook events already handled (a repeated delivery is ignored).
CREATE TABLE IF NOT EXISTS webhook_event (
  event_id   VARCHAR(80) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  event_type VARCHAR(60) CHARACTER SET ascii NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (event_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
