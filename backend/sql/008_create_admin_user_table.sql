-- Admin / staff accounts for the admin app. Safe to run repeatedly: only creates the table if it is missing.
-- It never drops, truncates or alters existing tables or data.
-- password_hash holds a bcrypt hash (never the password). role: 'admin' (full access) or 'staff' (create / edit, no delete).
CREATE TABLE IF NOT EXISTS admin_user (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  email         VARCHAR(190) NOT NULL,
  full_name     VARCHAR(100) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role          ENUM('admin','staff') NOT NULL DEFAULT 'staff',
  status        TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = active, 0 = disabled',
  last_login_at TIMESTAMP NULL DEFAULT NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_admin_user_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
