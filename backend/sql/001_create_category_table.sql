-- Safe to run on an existing database: only creates the table if it is missing.
-- It never drops, truncates or alters existing tables or data.
-- An existing table with the old numeric id is converted to UUID by `npm run migrate`
-- (see scripts/uuid-migration.js), not by this file.
CREATE TABLE IF NOT EXISTS category (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  category_name VARCHAR(100) NOT NULL,
  description   TEXT NULL,
  image         VARCHAR(255) NULL,
  status        TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = active, 0 = inactive',
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_category_name (category_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
