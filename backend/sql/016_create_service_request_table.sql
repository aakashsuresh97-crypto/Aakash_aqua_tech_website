-- Service / AMC requests (public form, optionally linked to a signed-in customer). Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS service_request (
  id             CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  customer_id    CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  name           VARCHAR(100) NOT NULL,
  mobile         VARCHAR(15) NOT NULL,
  email          VARCHAR(190) NULL,
  city           VARCHAR(80) NULL,
  pin_code       VARCHAR(10) NULL,
  address        VARCHAR(500) NULL,
  service_type   ENUM('installation','repair','amc','filter_change','other') NOT NULL DEFAULT 'repair',
  product_note   VARCHAR(200) NULL COMMENT 'brand / model of the purifier',
  preferred_date DATE NULL,
  description    TEXT NULL,
  amc_plan_id    CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NULL,
  status         ENUM('new','assigned','in_progress','completed','cancelled') NOT NULL DEFAULT 'new',
  assigned_to    VARCHAR(100) NULL,
  admin_notes    TEXT NULL,
  ip_address     VARCHAR(45) NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_service_status (status, created_at),
  KEY idx_service_customer (customer_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
