-- Blog. status draft/published; only published posts with published_at <= now are public. Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS blog_post (
  id               CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  slug             VARCHAR(200) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  title            VARCHAR(250) NOT NULL,
  excerpt          VARCHAR(500) NULL,
  content_html     MEDIUMTEXT NOT NULL COMMENT 'sanitised on save',
  image_url        VARCHAR(500) NULL,
  author           VARCHAR(100) NULL,
  status           ENUM('draft','published') NOT NULL DEFAULT 'draft',
  published_at     TIMESTAMP NULL DEFAULT NULL,
  seo_title        VARCHAR(255) NULL,
  meta_description VARCHAR(500) NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_blog_post_slug (slug),
  KEY idx_blog_show (status, published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
