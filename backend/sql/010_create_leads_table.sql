-- Enquiries: "Book Your Free Demo" popup and the contact form. Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS leads (
  id             CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  first_name     VARCHAR(60) NOT NULL,
  last_name      VARCHAR(60) NULL,
  mobile         VARCHAR(15) NOT NULL,
  email          VARCHAR(190) NULL,
  city           VARCHAR(80) NULL,
  pin_code       VARCHAR(10) NULL,
  interest       ENUM('Water Purifier','Water Softener','AMC-Service','Other') NOT NULL DEFAULT 'Other',
  address        VARCHAR(500) NULL,
  message        TEXT NULL,
  source         ENUM('demo','contact','other') NOT NULL DEFAULT 'demo',
  status         ENUM('new','contacted','qualified','converted','closed','spam') NOT NULL DEFAULT 'new',
  notes          TEXT NULL,
  terms_accepted TINYINT(1) NOT NULL DEFAULT 0,
  page_url       VARCHAR(500) NULL,
  ip_address     VARCHAR(45) NULL,
  user_agent     VARCHAR(255) NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_leads_status_created (status, created_at),
  KEY idx_leads_mobile (mobile),
  KEY idx_leads_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
