-- Customer accounts (mobile OTP login). Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS customer (
  id            CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  mobile        CHAR(10) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT '10-digit Indian mobile',
  name          VARCHAR(100) NULL,
  email         VARCHAR(190) NULL,
  status        TINYINT(1) NOT NULL DEFAULT 1,
  last_login_at TIMESTAMP NULL DEFAULT NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_customer_mobile (mobile)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_address (
  id          CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'UUID, generated by the API',
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  label       VARCHAR(40) NULL,
  full_name   VARCHAR(100) NOT NULL,
  mobile      CHAR(10) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  line1       VARCHAR(200) NOT NULL,
  line2       VARCHAR(200) NULL,
  city        VARCHAR(80) NOT NULL,
  state       VARCHAR(80) NOT NULL,
  pin_code    CHAR(6) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  is_default  TINYINT(1) NOT NULL DEFAULT 0,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_address_customer (customer_id),
  CONSTRAINT fk_address_customer FOREIGN KEY (customer_id) REFERENCES customer (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- One row per OTP sent. Only a hash of the code is stored.
CREATE TABLE IF NOT EXISTS otp_request (
  id         CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  mobile     CHAR(10) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  code_hash  CHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
  expires_at DATETIME NOT NULL,
  attempts   TINYINT UNSIGNED NOT NULL DEFAULT 0,
  consumed   TINYINT(1) NOT NULL DEFAULT 0,
  ip_address VARCHAR(45) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_otp_mobile_created (mobile, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
